/** คืนหมวดที่พบในข้อความ เรียงจากพบคำมากไปน้อย */
export function detectCategories(text: string): string[] {
  const t = text.toLowerCase();
  const hits: [string, number][] = [];
  for (const [category, words] of Object.entries(CATEGORY_KEYWORDS)) {
    const n = words.filter((w) => t.includes(w)).length;
    if (n > 0) hits.push([category, n]);
  }
  return hits.sort((a, b) => b[1] - a[1]).map(([c]) => c);
}

export const ALL_KEYWORDS = Object.values(CATEGORY_KEYWORDS).flat();
